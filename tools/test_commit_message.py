from __future__ import annotations

import shutil
import subprocess
import sys
import unittest
import uuid
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
CHECKER = TOOLS / "check_commit_message.py"
sys.path.insert(0, str(TOOLS))

import check_commit_message as checker  # noqa: E402

TEMP_ROOT = TOOLS.parent / ".cache" / "commit-message-tests"

MAINTAINER = "iain.chesworth@gmail.com"

# The forbidden markers are assembled from pieces so that a repository-wide
# scan for attribution strings only finds this test file's intent, not a stray
# attribution.
CO_AUTHOR = "Co-" + "authored-by"
SIGN_OFF = "Signed-" + "off-by"
GENERATED = "Generated"
ROBOT = "\U0001f916"


class ScanTests(unittest.TestCase):
    def test_clean_message(self) -> None:
        message = (
            "Add async contract tests\n"
            "\n"
            "The suite proves work tracking and exactly-once completion.\n"
        )
        self.assertEqual(checker.scan_message(message), [])

    def test_co_authored_by_trailer(self) -> None:
        violations = checker.scan_message(f"Add a thing\n\n{CO_AUTHOR}: Someone <x@y>\n")
        self.assertEqual(len(violations), 1)
        self.assertIn("trailer", violations[0].reason)

    def test_signed_off_by_trailer(self) -> None:
        violations = checker.scan_message(f"Add a thing\n\n{SIGN_OFF}: Someone <x@y>\n")
        self.assertEqual(len(violations), 1)

    def test_generated_by_statement(self) -> None:
        violations = checker.scan_message(f"Add a thing\n\n{GENERATED} by a tool.\n")
        self.assertEqual(len(violations), 1)
        self.assertIn("generated-by", violations[0].reason)

    def test_generated_with_tool_emoji(self) -> None:
        violations = checker.scan_message(
            f"Add a thing\n\n{ROBOT} {GENERATED} with [Claude Code](https://claude.ai)\n"
        )
        self.assertEqual(len(violations), 1)

    def test_tool_attribution_mid_sentence(self) -> None:
        violations = checker.scan_message(
            f"Add a thing\n\nThis was {GENERATED.lower()} by ChatGPT from a prompt.\n"
        )
        self.assertEqual(len(violations), 1)
        self.assertIn("tool attribution", violations[0].reason)

    def test_ordinary_prose_is_allowed(self) -> None:
        message = (
            "Fix the parser\n"
            "\n"
            "The previous text was generated by the grammar table and no longer\n"
            "matched the specification.\n"
        )
        self.assertEqual(checker.scan_message(message), [])


class RangeTests(unittest.TestCase):
    def setUp(self) -> None:
        TEMP_ROOT.mkdir(parents=True, exist_ok=True)
        self.root = TEMP_ROOT / uuid.uuid4().hex
        self.root.mkdir()
        self.git("init", "-q")
        self.git("config", "user.name", "Test Maintainer")
        self.git("config", "user.email", MAINTAINER)
        self.git("config", "commit.gpgsign", "false")

    def tearDown(self) -> None:
        shutil.rmtree(self.root, ignore_errors=True)

    def git(self, *arguments: str) -> str:
        result = subprocess.run(
            ["git", *arguments],
            cwd=self.root,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        if result.returncode != 0:
            raise AssertionError(result.stderr)
        return result.stdout

    def commit(self, message: str, email: str = MAINTAINER) -> str:
        self.git(
            "-c", f"user.email={email}", "commit", "-q", "--allow-empty", "-m", message
        )
        return self.git("rev-parse", "HEAD").strip()

    def run_checker(self, *arguments: str) -> subprocess.CompletedProcess:
        return subprocess.run(
            [sys.executable, str(CHECKER), "--range", "HEAD", *arguments],
            cwd=self.root,
            capture_output=True,
            text=True,
        )

    def test_clean_commit_passes(self) -> None:
        self.commit("Add a feature\n\nIt does the thing.\n")
        result = self.run_checker("--author-email", MAINTAINER)
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_attribution_fails(self) -> None:
        self.commit(f"Add a feature\n\n{CO_AUTHOR}: Someone <x@y>\n")
        result = self.run_checker("--author-email", MAINTAINER)
        self.assertEqual(result.returncode, 1)
        self.assertIn("attribution trailer", result.stderr)

    def test_wrong_author_fails(self) -> None:
        self.commit("Add a feature\n", email="someone@example.test")
        result = self.run_checker("--author-email", MAINTAINER)
        self.assertEqual(result.returncode, 1)
        self.assertIn("is not the maintainer", result.stderr)

    def test_missing_range_is_not_an_error(self) -> None:
        self.commit("Add a feature\n")
        result = subprocess.run(
            [sys.executable, str(CHECKER), "--range", "HEAD..HEAD"],
            cwd=self.root,
            capture_output=True,
            text=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == "__main__":
    unittest.main()
