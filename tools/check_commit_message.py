"""Reject attribution trailers and generated-by statements in commits.

The repository has a single committer: its maintainer.  Commits must carry the
maintainer's authorship and nothing else - no ``Co-authored-by:`` or other
trailers, no "generated by/with" statements, no AI or tool attribution.

Usage
-----
    python tools/check_commit_message.py .git/COMMIT_EDITMSG
    git log --format=%B -1 | python tools/check_commit_message.py --stdin
    python tools/check_commit_message.py --commit HEAD
    python tools/check_commit_message.py --range origin/main..HEAD \
        --author-email iain.chesworth@gmail.com

Exit status is 0 when every checked message is clean, 1 otherwise.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

# Trailer keys that must never appear, whether or not the value looks like an
# attribution to a person.
TRAILER_KEYS = (
    "co-authored-by",
    "signed-off-by",
    "signed-off",
    "generated-by",
    "assisted-by",
    "written-by",
    "authored-by",
    "contributed-by",
    "sponsored-by",
    "reviewed-by",
    "tested-by",
    "acked-by",
)

# Lines that begin with one of these phrases are attribution statements.
GENERATED_PREFIXES = (
    "generated by",
    "generated with",
    "created by",
    "created with",
    "written by",
    "written with",
    "made with",
)

# Words that identify an AI or tool attribution anywhere on a line.
TOOL_WORDS = (
    "ai",
    "gpt",
    "chatgpt",
    "claude",
    "copilot",
    "deepseek",
    "openai",
    "anthropic",
    "cursor",
    "llm",
    "codex",
    "assistant",
    "robot",
)

GENERATED_ANYWHERE_RE = re.compile(r"\b(generated|created|written|produced)\s+(by|with)\b")

ROBOT_MARKERS = ("\U0001f916",)  # robot emoji


@dataclass
class Violation:
    commit: str
    line: int
    text: str
    reason: str

    def render(self) -> str:
        prefix = f"{self.commit}: " if self.commit else ""
        return f"{prefix}line {self.line}: {self.reason}: {self.text.strip()!r}"


def scan_message(message: str, commit: str = "") -> list[Violation]:
    """Returns every attribution problem in one commit message."""
    violations: list[Violation] = []
    for number, line in enumerate(message.splitlines(), start=1):
        stripped = line.strip()
        if not stripped:
            continue
        lowered = stripped.lower()

        key = lowered.split(":", 1)[0].strip() if ":" in lowered else ""
        if key in TRAILER_KEYS:
            violations.append(Violation(commit, number, line, "attribution trailer"))
            continue

        if any(marker in line for marker in ROBOT_MARKERS):
            violations.append(Violation(commit, number, line, "robot marker"))
            continue

        if any(lowered.startswith(prefix) for prefix in GENERATED_PREFIXES):
            violations.append(Violation(commit, number, line, "generated-by statement"))
            continue

        if GENERATED_ANYWHERE_RE.search(lowered) and any(
            word in lowered for word in TOOL_WORDS
        ):
            violations.append(Violation(commit, number, line, "tool attribution"))
            continue

        if "co-authored-by" in lowered:
            violations.append(Violation(commit, number, line, "attribution trailer"))

    return violations


def git(*arguments: str) -> str:
    result = subprocess.run(
        ["git", *arguments], capture_output=True, text=True, encoding="utf-8"
    )
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or "git failed")
    return result.stdout


def commits_in_range(specification: str) -> list[str]:
    if ".." not in specification:
        return [git("rev-parse", specification).strip()]

    before, _, after = specification.partition("..")
    after = after or "HEAD"

    # An all-zero "before" is how GitHub reports a new branch.
    if before and set(before) == {"0"}:
        before = ""

    if before:
        output = git("rev-list", "--no-merges", "--reverse", f"{before}..{after}")
    else:
        output = git("rev-list", "-n", "1", after)
    return [line.strip() for line in output.splitlines() if line.strip()]


def author_of(commit: str) -> str:
    return git("show", "-s", "--format=%ae", commit).strip()


def message_of(commit: str) -> str:
    return git("show", "-s", "--format=%B", commit)


def check_commits(revs: list[str], author_email: str | None) -> list[str]:
    problems: list[str] = []
    for commit in revs:
        if author_email:
            author = author_of(commit).lower()
            if author != author_email.lower():
                problems.append(
                    f"{commit}: author {author!r} is not the maintainer "
                    f"({author_email!r})"
                )
        for violation in scan_message(message_of(commit), commit[:12]):
            problems.append(violation.render())
    return problems


def read_message(arguments: argparse.Namespace) -> str:
    if arguments.stdin:
        return sys.stdin.read()
    if arguments.message_file:
        return Path(arguments.message_file).read_text(encoding="utf-8")
    raise SystemExit("error: give a message file, --stdin, --commit or --range")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Reject attribution trailers and generated-by statements."
    )
    parser.add_argument("message_file", nargs="?", help="path to a commit message")
    parser.add_argument("--stdin", action="store_true", help="read the message from stdin")
    parser.add_argument("--commit", help="check one commit")
    parser.add_argument("--range", help="check commits in a git revision range")
    parser.add_argument(
        "--author-email",
        help="require this author email (case-insensitive) on every checked commit",
    )
    arguments = parser.parse_args(argv)

    try:
        if arguments.commit or arguments.range:
            revs = (
                [arguments.commit]
                if arguments.commit
                else commits_in_range(arguments.range)
            )
            if not revs:
                print("no commits to check")
                return 0
            problems = check_commits(revs, arguments.author_email)
        else:
            problems = [
                violation.render()
                for violation in scan_message(read_message(arguments))
            ]
    except (OSError, RuntimeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        print(
            "error: commits must be authored by the maintainer and must not "
            "carry attribution trailers, generated-by statements or tool "
            "attribution",
            file=sys.stderr,
        )
        return 1

    print("commit message(s) OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
